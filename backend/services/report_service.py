"""
Forensic Reporting & Court Exhibit Dossier Service for ForenVision AI.
Aggregates real database records from cases, evidence inventory, chain-of-custody logs,
and forensic analysis results (Image Forensics/ELA, YOLO Object Detection, Fingerprint SIFT-RANSAC,
Controlled Face Analysis, and Witness Sketch Review).
Generates authenticated, court-admissible PDF reports via ReportLab with digital digests.

FORENSIC PRINCIPLES & LEGAL INVARIANTS:
1. Zero Fabrication: Reports use only real authorized database records. Never invents missing
   findings or claims that experimental analysis is legally validated.
2. Perspective Separation: Explicitly separates Objective Physical Observations, Automated
   Algorithmic Diagnostics, and Human Investigator Interpretations.
3. Selective Module Inclusion: Face, fingerprint, and sketch sections appear ONLY when actual
   results exist on the case docket.
4. Transparent Gaps & Limitations: Incomplete data, stripped metadata, and model constraints
   are explicitly documented.
5. Access Control: Report generation, retrieval, and PDF downloads enforce strict case-level RBAC.
"""

