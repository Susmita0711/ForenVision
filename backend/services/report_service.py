    def _save_report_record(self, record: Dict[str, Any]) -> None:
        """Persist report record to MongoDB and memory store."""
        self._memory_reports[record["reportNumber"]] = record
        db = db_service.get_db()
        if db is not None:
            try:
                db["forensic_reports"].replace_one(
                    {"reportNumber": record["reportNumber"]},
                    record,
                    upsert=True,
                )
            except PyMongoError:
                pass

    def list_reports(
        self,
        user: Dict[str, Any],
        case_id_or_number: Optional[str] = None,
    ) -> List[Dict[str, Any]]:
        """List all reports accessible to user under case clearance RBAC."""
        reports: List[Dict[str, Any]] = []

        # 1. MongoDB Query
        db = db_service.get_db()
        if db is not None:
            try:
                query: Dict[str, Any] = {}
                if case_id_or_number:
                    query = {"$or": [{"caseId": case_id_or_number}, {"caseNumber": case_id_or_number}]}
                cursor = db["forensic_reports"].find(query).sort("createdAt", -1)
                for r in cursor:
                    r.pop("_id", None)
                    reports.append(r)
            except PyMongoError:
                pass

        # 2. Merge memory reports
        for mem_rep in self._memory_reports.values():
            if not any(r["reportNumber"] == mem_rep["reportNumber"] for r in reports):
                if not case_id_or_number or (mem_rep.get("caseId") == case_id_or_number or mem_rep.get("caseNumber") == case_id_or_number):
                    reports.append(dict(mem_rep))

        # Filter by Case Clearance Authorization
        accessible_reports: List[Dict[str, Any]] = []
        for r in reports:
            case_id = r.get("caseId")
            if case_id:
                raw_case = case_service._find_raw_case_doc(case_id)
                if raw_case and not case_service.user_can_access_case(user, raw_case):
                    continue
            accessible_reports.append(r)

        accessible_reports.sort(key=lambda r: str(r.get("createdAt", "")), reverse=True)
        return accessible_reports

    def get_report_by_id(
        self,
        report_id_or_number: str,
        user: Dict[str, Any],
    ) -> Optional[Dict[str, Any]]:
        """Retrieve report metadata by ID, validating user case clearance."""
        report = self._memory_reports.get(report_id_or_number)
        if not report:
            for r in self._memory_reports.values():
                if r.get("id") == report_id_or_number or r.get("reportNumber") == report_id_or_number:
                    report = r
                    break

        if not report:
            db = db_service.get_db()
            if db is not None:
                try:
                    report = db["forensic_reports"].find_one({
                        "$or": [
                            {"id": report_id_or_number},
                            {"reportId": report_id_or_number},
                            {"reportNumber": report_id_or_number},
                        ]
                    })
                except PyMongoError:
                    pass

        if not report:
            return None

        # Verify Case Access
        case_id = report.get("caseId")
        if case_id:
            raw_case = case_service._find_raw_case_doc(case_id)
            if raw_case and not case_service.user_can_access_case(user, raw_case):
                raise PermissionError("Access denied: You lack clearance to access reports under this case docket.")

        clean = dict(report)
        clean.pop("_id", None)
        return clean

    def get_report_pdf_bytes(
        self,
        report_id_or_number: str,
        user: Dict[str, Any],
    ) -> Tuple[bytes, str]:
        """Retrieve PDF bytes for an authorized report."""
        report = self.get_report_by_id(report_id_or_number, user)
        if not report:
            raise FileNotFoundError(f"Report '{report_id_or_number}' not found.")

        report_num = report.get("reportNumber", report_id_or_number)
        filename = report.get("pdf", {}).get("filename", f"{report_num}_dossier.pdf")

        # Check memory
        if report_num in self._memory_pdf_files:
            return self._memory_pdf_files[report_num], filename

        # Check disk vault
        case_number = report.get("caseNumber", "UNKNOWN-CASE")
        pdf_disk_path = self._vault_dir / case_number / "reports" / f"{report_num}.pdf"
        if pdf_disk_path.is_file():
            try:
                with open(pdf_disk_path, "rb") as f:
                    return f.read(), filename
            except OSError as e:
                raise RuntimeError(f"Failed to read report PDF from vault: {str(e)}")

        # Fallback: Regenerate PDF on the fly from stored report document
        rebuilt_pdf = self._build_pdf_document(report)
        self._memory_pdf_files[report_num] = rebuilt_pdf
        return rebuilt_pdf, filename


